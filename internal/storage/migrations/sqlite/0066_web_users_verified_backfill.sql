-- Аккаунты, заведённые до появления подтверждения, считаются подтверждёнными.
--
-- Иначе апдейт разом отрезал бы всех действующих покупателей от оплаты и от
-- их же тарифов по списку — за то, что во время регистрации подтверждать было
-- нечем. Проходит один раз: строки, созданные после миграции, сюда не попадают.
UPDATE web_users SET email_verified_at = CASE WHEN created_at <> '' THEN created_at ELSE '1970-01-01T00:00:00Z' END WHERE email_verified_at = '';
