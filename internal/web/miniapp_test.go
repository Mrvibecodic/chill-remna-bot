package web

import "testing"

// Подпись Telegram фиксируется при открытии мини-аппа и не обновляется, а
// фронт при истёкшем пропуске повторяет обмен ТОЙ ЖЕ подписью. Если окно
// подписи короче жизни пропуска, обновиться нечем: человек с открытым
// мини-аппом упирается в 401 и дальше не проходит.
func TestInitDataOutlivesSession(t *testing.T) {
	if initDataTTL <= jwtTTL {
		t.Fatalf("окно подписи (%s) не шире жизни пропуска (%s) — обновление пропуска недостижимо",
			initDataTTL, jwtTTL)
	}
}
