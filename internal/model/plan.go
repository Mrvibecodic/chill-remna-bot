package model

import (
	"crypto/sha256"
	"encoding/hex"
	"encoding/json"
)

// PlanSnapshot — условия сделки, зафиксированные в момент выставления счёта.
//
// Зачем: до сих пор о покупке хранилось только число месяцев, а лимиты и
// сквады при продлении, автосписании и добивании счёта реконсилятором брались
// из ТЕКУЩЕГО конфига. Админ поднял лимит устройств — и он молча менялся у
// всех, кто продлевается; наоборот, снизил — и человек терял то, за что уже
// заплатил. Снимок делает сделку самодостаточной: продлеваем ровно то, что
// продали.
//
// Снимок хранится JSON-строкой в отдельных колонках (payments,
// pending_invoices, p2p_requests, autopay, users). Колонки объявлены
// NOT NULL DEFAULT ”: вставки везде перечисляют поля явно, поэтому
// предыдущий образ бота, который про них не знает, продолжает писать свои
// строки — откат остаётся безопасным.
type PlanSnapshot struct {
	// Code и Name — опознание тарифа, которым продана эта сделка. В отпечаток
	// условий они не входят: переименование тарифа условий не меняет.
	Code string `json:"code,omitempty"`
	Name string `json:"name,omitempty"`

	Months int `json:"months"`
	// Days — исходная длительность сделки в днях, когда источник знал её
	// точнее месяцев (импорт истории remnashop: месяцы там восстановлены как
	// (дни+15)/30). Опознание сделки, а не условие — в отпечаток не входит.
	Days        int      `json:"days,omitempty"`
	TrafficGB   int      `json:"traffic_gb"`
	DeviceLimit int      `json:"device_limit"`
	Strategy    string   `json:"strategy,omitempty"`
	IntSquads   []string `json:"int_squads,omitempty"`
	ExtSquad    string   `json:"ext_squad,omitempty"`

	// AddSub — продана ли с этой сделкой доп-подписка. Указатель, а не bool:
	// в снимках, снятых до появления опции, поля нет, и это означает «как
	// раньше» — опция есть, пока включена глобально. Явный false появляется
	// только у тарифов, проданных без опции.
	AddSub *bool `json:"addsub,omitempty"`

	Price    string `json:"price,omitempty"`
	Currency string `json:"currency,omitempty"`
	// Paid — фактически уплаченная цена сделки в валюте сетки, когда её
	// удалось разобрать из суммы платежа. Отличается от Price при скидочных
	// переопределениях цены по способу оплаты; зачёт остатка при смене
	// тарифа считает по ней — иначе скидочная покупка зачлась бы по полной
	// цене. Опознание экономики сделки, не условие — в отпечаток не входит.
	Paid string `json:"paid,omitempty"`
	// BoughtDays — накопленное ОПЛАЧЕННОЕ окно в днях: сколько из оставшегося
	// срока куплено деньгами (продления складываются, бонусные дни рефералок
	// и промокодов сюда не попадают). Зачёт остатка при смене тарифа
	// конвертирует не больше этого окна; 0 (старые снимки, откат) — окно
	// одной сделки (Days или Months×30). Экономика сделки, не условие — в
	// отпечаток не входит.
	BoughtDays int `json:"bought_days,omitempty"`
}

// AddSubSold — продана ли доп-подписка этой сделкой. Отсутствие снимка или
// поля — «как раньше»: опция есть, пока включена глобально.
func (s *PlanSnapshot) AddSubSold() bool {
	if s == nil || s.AddSub == nil {
		return true
	}
	return *s.AddSub
}

// TrafficBytes — лимит трафика снимка в байтах (0 = безлимит).
func (s *PlanSnapshot) TrafficBytes() int64 {
	if s == nil || s.TrafficGB <= 0 {
		return 0
	}
	return int64(s.TrafficGB) * 1024 * 1024 * 1024
}

// Encode сериализует снимок для хранения. Пустой снимок пишется пустой
// строкой, а не "null": так колонка остаётся совместимой с DEFAULT ”.
func (s *PlanSnapshot) Encode() string {
	if s == nil {
		return ""
	}
	b, err := json.Marshal(s)
	if err != nil {
		return ""
	}
	return string(b)
}

// Fingerprint — короткий отпечаток условий сделки. Нужен, чтобы дешёво
// заметить, что условия изменились (например, перед уведомлением об
// изменившемся автопродлении). В ключ идемпотентности платежей отпечаток
// намеренно НЕ входит: там повтор обязан попадать в тот же платёж.
func (s *PlanSnapshot) Fingerprint() string {
	if s == nil {
		return "0"
	}
	// Код и имя тарифа в отпечаток НЕ входят: это опознание сделки и её
	// оформление, а не условия. Иначе первое же обновление бота (в снимках
	// появился код) и любое переименование тарифа рассылали бы всем
	// подписчикам «условия автопродления изменились», хотя не изменилось
	// ничего.
	cond := *s
	cond.Code = ""
	cond.Name = ""
	cond.Days = 0
	cond.Paid = ""
	cond.BoughtDays = 0
	// Доп-подписка «есть» канонизируется в отсутствие поля: старые снимки без
	// поля означают ровно это, и первое обновление бота не должно рассылать
	// «условия изменились» всем, у кого ничего не изменилось. В отпечатке
	// участвует только явное «без опции».
	if cond.AddSub != nil && *cond.AddSub {
		cond.AddSub = nil
	}
	sum := sha256.Sum256([]byte(cond.Encode()))
	return hex.EncodeToString(sum[:4])
}

// DecodePlanSnapshot читает снимок из хранилища. Пустая строка и битый JSON
// дают nil — вызывающий обязан уметь работать без снимка (строки, созданные
// до появления колонок, и строки, записанные предыдущим образом бота).
func DecodePlanSnapshot(raw string) *PlanSnapshot {
	if raw == "" {
		return nil
	}
	var s PlanSnapshot
	if err := json.Unmarshal([]byte(raw), &s); err != nil {
		return nil
	}
	return &s
}
